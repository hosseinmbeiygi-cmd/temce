const IMPORTANCE_WEIGHTS: Record<string, number> = {
  حیاتی: 1,
  بالا: 0.82,
  متوسط: 0.6,
};

const CADENCE_WEIGHTS: Record<string, number> = {
  "لحظه‌ای": 1,
  روزانه: 0.95,
  هفتگی: 0.9,
  ماهانه: 0.8,
  فصلی: 0.72,
  سالانه: 0.62,
  رویدادمحور: 0.85,
};

const STATUS_WEIGHTS: Record<string, number> = {
  "بررسی‌نشده / آماده تکمیل": 0.7,
  "آماده تکمیل": 0.7,
  "آماده بررسی": 0.82,
  "بررسی‌شده": 1,
};

const STATUS_LABELS: Record<string, string> = {
  "بررسی‌نشده / آماده تکمیل": "آماده تکمیل",
  "آماده تکمیل": "آماده تکمیل",
  "آماده بررسی": "آماده بررسی",
  "بررسی‌شده": "بررسی‌شده",
};

const IMPORTANCE_LABELS: Record<string, string> = {
  حیاتی: "حیاتی",
  بالا: "بالا",
  متوسط: "متوسط",
};

export function normalizeChecklistStatus(status: string): string {
  const value = status.trim();
  if (!value) return "نامشخص";
  if (value.includes("بررسی‌شده")) return "بررسی‌شده";
  if (value.includes("آماده بررسی")) return "آماده بررسی";
  if (value.includes("آماده تکمیل")) return "آماده تکمیل";
  return STATUS_LABELS[value] ?? value;
}

export function normalizeChecklistImportance(importance: string): string {
  const value = importance.trim();
  if (!value) return "متوسط";
  if (value.includes("حیاتی")) return "حیاتی";
  if (value.includes("بالا")) return "بالا";
  if (value.includes("متوسط")) return "متوسط";
  return IMPORTANCE_LABELS[value] ?? value;
}

function weightForCadence(cadence: string): number {
  const value = cadence.trim();
  if (!value) return 0.7;
  for (const [key, weight] of Object.entries(CADENCE_WEIGHTS)) {
    if (value.includes(key)) return weight;
  }
  return value.includes("روز") ? 0.9 : value.includes("هفته") ? 0.85 : 0.75;
}

function weightForImportance(importance: string): number {
  const value = normalizeChecklistImportance(importance);
  return IMPORTANCE_WEIGHTS[value] ?? 0.6;
}

function weightForStatus(status: string): number {
  const value = normalizeChecklistStatus(status);
  return STATUS_WEIGHTS[value] ?? 0.72;
}

export function scoreChecklistItem(item: FundChecklistItem): number {
  const importanceWeight = weightForImportance(item.importance);
  const cadenceWeight = weightForCadence(item.cadence);
  const statusWeight = weightForStatus(item.status);
  const evidenceWeight = item.formula.trim() && item.source.trim() ? 1 : 0.88;
  const raw = 100 * importanceWeight * cadenceWeight * statusWeight * evidenceWeight;
  return Math.max(0, Math.min(100, Math.round(raw)));
}

export function getChecklistSeverityColor(score: number): string {
  if (score >= 80) return "text-accent-emerald";
  if (score >= 60) return "text-primary-300";
  if (score >= 40) return "text-accent-amber";
  return "text-accent-rose";
}

export function getChecklistSeverityBg(score: number): string {
  if (score >= 80) return "bg-accent-emerald/15";
  if (score >= 60) return "bg-primary-600/15";
  if (score >= 40) return "bg-accent-amber/15";
  return "bg-accent-rose/15";
}

export function groupChecklistItems(items: FundChecklistItem[] = FUND_CHECKLIST_ITEMS): FundChecklistAreaSummary[] {
  const groups = new Map<string, FundChecklistItem[]>();
  for (const item of items) {
    if (!groups.has(item.area)) groups.set(item.area, []);
    groups.get(item.area)!.push(item);
  }

  return FUND_CHECKLIST_AREA_ORDER.map((area) => {
    const areaItems = groups.get(area) ?? [];
    const scores = areaItems.map(scoreChecklistItem);
    const criticalCount = areaItems.filter((item) => normalizeChecklistImportance(item.importance) === "حیاتی").length;
    const highCount = areaItems.filter((item) => normalizeChecklistImportance(item.importance) === "بالا").length;
    const mediumCount = areaItems.filter((item) => normalizeChecklistImportance(item.importance) === "متوسط").length;
    const pendingCount = areaItems.filter((item) => normalizeChecklistStatus(item.status) !== "بررسی‌شده").length;
    const averageScore = scores.length ? Math.round(scores.reduce((sum, value) => sum + value, 0) / scores.length) : 0;
    return {
      area,
      itemCount: areaItems.length,
      criticalCount,
      highCount,
      mediumCount,
      pendingCount,
      averageScore,
    };
  });
}

export function summarizeChecklist(items: FundChecklistItem[] = FUND_CHECKLIST_ITEMS): FundChecklistSummary {
  const scores = items.map(scoreChecklistItem);
  const criticalCount = items.filter((item) => normalizeChecklistImportance(item.importance) === "حیاتی").length;
  const highCount = items.filter((item) => normalizeChecklistImportance(item.importance) === "بالا").length;
  const mediumCount = items.filter((item) => normalizeChecklistImportance(item.importance) === "متوسط").length;
  const pendingCount = items.filter((item) => normalizeChecklistStatus(item.status) !== "بررسی‌شده").length;
  const averageScore = scores.length ? Math.round(scores.reduce((sum, value) => sum + value, 0) / scores.length) : 0;
  return {
    totalItems: items.length,
    totalAreas: FUND_CHECKLIST_AREA_ORDER.length,
    criticalCount,
    highCount,
    mediumCount,
    pendingCount,
    averageScore,
  };
}
